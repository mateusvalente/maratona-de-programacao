# Relação do algoritmo com o problema
# Objetivo: Ler dois inteiros, somá-los e apresentar o resultado com o rótulo X.
# Entrada: Dois inteiros, um em cada linha.
# Saída: A soma no formato X = resultado.
#
# Passo a passo
# 1. Ler o primeiro inteiro em A.
# 2. Ler o segundo inteiro em B.
# 3. Calcular A + B.
# 4. Imprimir X = soma.

# Implementação completa
a = int(input())
b = int(input())

soma = a + b

print(f"X = {soma}")
